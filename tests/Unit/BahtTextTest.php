<?php

declare(strict_types=1);

use App\Support\BahtText;

/**
 * เคสบังคับตามสเปกข้อ 4.2: 0, 0.25, 1000000, 1234567.89
 */
it('แปลงเคสที่สเปกระบุไว้ได้ถูกต้อง', function (string|int|float $amount, string $expected): void {
    expect(BahtText::convert($amount))->toBe($expected);
})->with([
    [0, 'ศูนย์บาทถ้วน'],
    [0.25, 'ยี่สิบห้าสตางค์'],
    [1000000, 'หนึ่งล้านบาทถ้วน'],
    [1234567.89, 'หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทแปดสิบเก้าสตางค์'],
]);

it('อ่านหลักสิบตามกฎภาษาไทย ไม่ใช่อ่านทีละหลัก', function (string $amount, string $expected): void {
    expect(BahtText::convert($amount))->toBe($expected);
})->with([
    // 1 ในหลักสิบอ่านว่า "สิบ" ไม่ใช่ "หนึ่งสิบ"
    ['10', 'สิบบาทถ้วน'],
    // 2 ในหลักสิบอ่านว่า "ยี่สิบ"
    ['20', 'ยี่สิบบาทถ้วน'],
    // 1 ในหลักหน่วยเมื่อมีหลักอื่นนำหน้าอ่านว่า "เอ็ด"
    ['11', 'สิบเอ็ดบาทถ้วน'],
    ['21', 'ยี่สิบเอ็ดบาทถ้วน'],
    ['101', 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    ['1', 'หนึ่งบาทถ้วน'],
]);

it('อ่านตัวเลขทุกหลักจนถึงหลักแสนได้', function (): void {
    expect(BahtText::convert('987654'))
        ->toBe('เก้าแสนแปดหมื่นเจ็ดพันหกร้อยห้าสิบสี่บาทถ้วน');
});

it('ข้ามหลักที่เป็นศูนย์โดยไม่ทิ้งคำว่าศูนย์ไว้กลางประโยค', function (): void {
    expect(BahtText::convert('1000005'))->toBe('หนึ่งล้านห้าบาทถ้วน')
        ->and(BahtText::convert('305'))->toBe('สามร้อยห้าบาทถ้วน')
        ->and(BahtText::convert('1000'))->toBe('หนึ่งพันบาทถ้วน');
});

it('อ่านกลุ่มหลังคำว่าล้านที่มีค่าเป็นหนึ่งว่าเอ็ด', function (): void {
    expect(BahtText::convert('1000001'))->toBe('หนึ่งล้านเอ็ดบาทถ้วน');
});

it('อ่านจำนวนที่เกินสิบสามหลักได้โดยแบ่งกลุ่มละหกหลัก', function (): void {
    expect(BahtText::convert('1000000000000'))
        ->toBe('หนึ่งล้านล้านบาทถ้วน');
});

it('ปัดเศษเกินสองตำแหน่งก่อนอ่าน', function (): void {
    // 0.005 ปัดครึ่งขึ้นเป็น 0.01
    expect(BahtText::convert('0.005'))->toBe('หนึ่งสตางค์')
        ->and(BahtText::convert('1.994'))->toBe('หนึ่งบาทเก้าสิบเก้าสตางค์');
});

it('อ่านค่าติดลบโดยขึ้นต้นด้วยคำว่าลบ', function (): void {
    expect(BahtText::convert('-150.50'))->toBe('ลบหนึ่งร้อยห้าสิบบาทห้าสิบสตางค์');
});

it('ยอดที่ลงท้ายด้วยศูนย์สตางค์ต้องขึ้นคำว่าถ้วน', function (): void {
    expect(BahtText::convert('2500.00'))->toBe('สองพันห้าร้อยบาทถ้วน')
        ->and(BahtText::convert('2500.10'))->toBe('สองพันห้าร้อยบาทสิบสตางค์');
});
